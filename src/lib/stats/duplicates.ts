// Card 5 — Duplicates. De-duplication already runs during matching (each
// duplicate row carries `duplicateOf` = the canonical cite key). This surfaces
// it as a finding: which works were cited more than once, under which keys.
//
// The interesting signal: the SAME work appearing under DIFFERENT cite-key
// styles (e.g. `todorov_optimality_2004` alongside `todorov2004Optimality`) is
// the signature of two bibliographies merged without de-duplication — worth
// telling the owner about.

import type { ResultRow } from '../../types'

export interface DuplicateGroup {
  canonicalKey: string
  title: string
  citeKeys: string[] // canonical first, then the duplicates
  count: number // total entries collapsed into this one work (citeKeys.length)
  mixedKeyStyles: boolean // keys span more than one naming style
}

export interface DuplicateReport {
  groups: DuplicateGroup[]
  duplicatedWorks: number // number of works that had at least one duplicate
  totalCollapsed: number // duplicate rows removed from stats (== summary.duplicates)
  mixedStyleGroups: number // groups exhibiting the merged-bibliography signature
}

// Coarse cite-key style classifier. We only need to tell whether two keys were
// generated by different conventions, so a few orthogonal signals suffice.
export function citeKeyStyle(key: string): string {
  const hasUnderscore = /_/.test(key)
  const hasCamel = /[a-z][A-Z]/.test(key)
  const hasHyphen = /-/.test(key)
  const yearFirst = /^\d/.test(key)
  return [
    hasUnderscore ? 'u' : '',
    hasCamel ? 'c' : '',
    hasHyphen ? 'h' : '',
    yearFirst ? 'y' : '',
  ].join('') || 'flat'
}

export function computeDuplicateReport(rows: ResultRow[]): DuplicateReport {
  // canonical cite key -> the rows (canonical + duplicates) that share the work
  const dupRowsByCanon = new Map<string, ResultRow[]>()
  for (const r of rows) {
    if (!r.duplicateOf) continue
    const arr = dupRowsByCanon.get(r.duplicateOf) ?? []
    arr.push(r)
    dupRowsByCanon.set(r.duplicateOf, arr)
  }

  const canonByKey = new Map<string, ResultRow>()
  for (const r of rows) if (!r.duplicateOf) canonByKey.set(r.citeKey, r)

  const groups: DuplicateGroup[] = []
  let totalCollapsed = 0
  for (const [canonKey, dupRows] of dupRowsByCanon) {
    const canon = canonByKey.get(canonKey)
    const citeKeys = [canonKey, ...dupRows.map(r => r.citeKey)]
    const styles = new Set(citeKeys.map(citeKeyStyle))
    totalCollapsed += dupRows.length
    groups.push({
      canonicalKey: canonKey,
      title: canon?.title ?? dupRows[0]?.title ?? '—',
      citeKeys,
      count: citeKeys.length,
      mixedKeyStyles: styles.size > 1,
    })
  }

  // Most-duplicated first; then alphabetical for stable output.
  groups.sort((a, b) => b.count - a.count || a.canonicalKey.localeCompare(b.canonicalKey))

  return {
    groups,
    duplicatedWorks: groups.length,
    totalCollapsed,
    mixedStyleGroups: groups.filter(g => g.mixedKeyStyles).length,
  }
}
